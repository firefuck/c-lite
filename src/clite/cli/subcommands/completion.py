"""``clite completion bash|zsh|fish``: shell completion built from the real parser.

The script is generated by walking the argparse tree that ``main`` builds, so it always names
the current subcommands and flags — including a plugin's, when the plugin contributes one. No
list of command names is written down twice.

Dynamic values (profile names, model names, session ids) are completed by calling
``clite completion --values <kind>``, which reads the catalogue and prints one name per line.
That path is kept fast and never loads plugins or a model: it runs on every Tab.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field

_PROG = "clite"
_VALUE_KINDS = ("profiles", "models", "sessions")


def _clean(text: str, limit: int = 60) -> str:
    """Make a help string safe to embed in a shell script, on one line."""
    safe = "".join(char if char.isalnum() or char in " -_.,/" else " " for char in text.replace(":", " "))
    return " ".join(safe.split())[:limit]


@dataclass
class _Node:
    """One point in the parser tree: its flags and its subcommands."""

    flags: list[str] = field(default_factory=list)
    subcommands: dict[str, _Node] = field(default_factory=dict)
    help: str = ""


def _walk(parser: argparse.ArgumentParser) -> _Node:
    """Extract subcommands and flags from a parser, recursively.

    ``_choices_actions`` gives one entry per canonical name (aliases omitted), which keeps the
    suggested list clean.
    """
    node = _Node()
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for pseudo in action._choices_actions:
                name = pseudo.dest
                subparser = action.choices.get(name)
                if subparser is None or name in node.subcommands:
                    continue
                child = _walk(subparser)
                child.help = _clean(pseudo.help or "")
                node.subcommands[name] = child
        elif action.option_strings:
            node.flags.extend(option for option in action.option_strings if option.startswith("-"))
    return node


def _generate_bash(parser: argparse.ArgumentParser) -> str:
    tree = _walk(parser)
    top = " ".join(sorted(tree.subcommands))
    lines = [
        f"# bash completion for {_PROG}. Install with:",
        f"#   {_PROG} completion bash > /etc/bash_completion.d/{_PROG}",
        f"_{_PROG}_complete() {{",
        "    local cur prev",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '    local commands="' + top + '"',
        '    if [ "$COMP_CWORD" -eq 1 ]; then',
        '        COMPREPLY=($(compgen -W "$commands --help --version" -- "$cur"))',
        "        return",
        "    fi",
        '    case "$prev" in',
        "        -p|--profile)",
        f'            COMPREPLY=($(compgen -W "$({_PROG} completion --values profiles)" -- "$cur"))',
        "            return;;",
        "        -m|--model)",
        f'            COMPREPLY=($(compgen -W "$({_PROG} completion --values models)" -- "$cur"))',
        "            return;;",
        "        -r|--session)",
        f'            COMPREPLY=($(compgen -W "$({_PROG} completion --values sessions)" -- "$cur"))',
        "            return;;",
        "    esac",
        '    local sub="${COMP_WORDS[1]}"',
        '    case "$sub" in',
    ]
    for name in sorted(tree.subcommands):
        child = tree.subcommands[name]
        sub_names = " ".join(sorted(child.subcommands))
        flags = " ".join(sorted(set(child.flags)))
        lines.append(f"        {name})")
        lines.append(f'            COMPREPLY=($(compgen -W "{sub_names} {flags} --help" -- "$cur"))')
        lines.append("            return;;")
    lines += [
        "    esac",
        '    COMPREPLY=($(compgen -W "$commands" -- "$cur"))',
        "}",
        f"complete -F _{_PROG}_complete {_PROG}",
    ]
    return "\n".join(lines) + "\n"


def _generate_zsh(parser: argparse.ArgumentParser) -> str:
    tree = _walk(parser)
    top = " ".join(sorted(tree.subcommands))
    descriptions = " ".join(f"'{name}:{child.help}'" for name, child in sorted(tree.subcommands.items()))
    return (
        "\n".join(
            [
                f"#compdef {_PROG}",
                f"# zsh completion for {_PROG}. Install with:",
                f'#   {_PROG} completion zsh > "${{fpath[1]}}/_{_PROG}"',
                f"_{_PROG}() {{",
                "    local -a commands",
                f"    commands=({descriptions})",
                "    _arguments -C \\",
                '        "1:command:->command" \\',
                '        "*::arg:->args"',
                "    case $state in",
                "        command)",
                "            _describe 'command' commands ;;",
                "        args)",
                f'            _arguments "*:argument:(${top})" ;;',
                "    esac",
                "}",
                f"compdef _{_PROG} {_PROG}",
            ]
        )
        + "\n"
    )


def _generate_fish(parser: argparse.ArgumentParser) -> str:
    tree = _walk(parser)
    lines = [
        f"# fish completion for {_PROG}. Install with:",
        f"#   {_PROG} completion fish > ~/.config/fish/completions/{_PROG}.fish",
    ]
    for name, child in sorted(tree.subcommands.items()):
        lines.append(f"complete -c {_PROG} -n '__fish_use_subcommand' -a {name} -d '{child.help}'")
    lines.append(f"complete -c {_PROG} -l help")
    lines.append(f"complete -c {_PROG} -s p -l profile -x -a '({_PROG} completion --values profiles)'")
    lines.append(f"complete -c {_PROG} -s m -l model -x -a '({_PROG} completion --values models)'")
    lines.append(f"complete -c {_PROG} -s r -l session -x -a '({_PROG} completion --values sessions)'")
    return "\n".join(lines) + "\n"


def _values(kind: str) -> list[str]:
    """The dynamic values a shell completes, read without starting plugins or a model."""
    if kind == "profiles":
        from clite.core.profiles import list_profiles

        return [info.name for info in list_profiles()]
    if kind == "models":
        from clite.core.config import get_path, load_config
        from clite.providers.models import list_models

        try:
            provider = get_path(load_config(), "model.provider", "")
            if not provider:
                return []
            return [model.id for model in list_models(str(provider), refresh=False)]
        except Exception:  # noqa: BLE001 - completion must never fail a Tab
            return []
    if kind == "sessions":
        from clite.state import get_session_db

        try:
            return [str(row["id"]) for row in get_session_db().list_sessions(limit=50)]
        except Exception:  # noqa: BLE001
            return []
    return []


def run_completion(args: argparse.Namespace) -> int:
    if args.values is not None:
        for value in _values(args.values):
            print(value)
        return 0
    if args.shell is None:
        print("Say which shell: clite completion bash|zsh|fish")
        return 2
    # The parser is built here, not at import, so the completion script reflects plugins.
    from clite.cli.main import build_parser

    parser = build_parser()
    generators = {"bash": _generate_bash, "zsh": _generate_zsh, "fish": _generate_fish}
    print(generators[args.shell](parser), end="")
    return 0


def register(subparsers: argparse._SubParsersAction) -> None:
    parser = subparsers.add_parser(
        "completion",
        help="print a shell completion script for bash, zsh or fish",
        description="Print a completion script built from the current parser. "
        "`clite completion --values KIND` answers the dynamic parts.",
    )
    parser.add_argument(
        "shell", nargs="?", choices=("bash", "zsh", "fish"), help="the shell to generate a script for"
    )
    parser.add_argument(
        "--values",
        choices=_VALUE_KINDS,
        metavar="KIND",
        help=f"print the {', '.join(_VALUE_KINDS)} to complete, one per line",
    )
    parser.set_defaults(handler=run_completion)
