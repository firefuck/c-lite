#!/usr/bin/env python3
"""Build the user documentation site: ``website/content/`` -> ``website/build/``.

    python scripts/build_site.py                    # write website/build/
    python scripts/build_site.py --out /tmp/site    # somewhere else
    python scripts/build_site.py --check            # exit 1 on a page that cannot be built

The site is generated by this script rather than by a static-site framework. That keeps the
build to the standard library: the package installs without Node, and the docs job in CI must
not need a second toolchain to publish a page. What a framework would add -- navigation,
cross-links, a language switcher, a stylesheet -- is small enough to render here.

Layout of the source:

* ``website/content/<lang>/<slug>.md`` -- one file per page, in each language, same slug in
  both trees, so a reader can switch language on any page.
* ``website/static/`` -- copied into the root of the build as it is (stylesheet, favicon).

Everything in the pages is Markdown that GitHub also renders, so the same file reads correctly
in the repository. Links between pages are written as ``../guide/tools.md``; the builder turns
the ``.md`` into ``.html`` and links are relative, so the site works under any base path (a
GitHub Pages project site, a file:// preview, a plain static host).

The prose is written by hand; the reference pages are generated from the code by
``scripts/gen_docs.py`` and live in the same trees. Never edit those by hand.
"""

from __future__ import annotations

import argparse
import html
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "website" / "content"
STATIC = ROOT / "website" / "static"
DEFAULT_OUT = ROOT / "website" / "build"
LANGUAGES = ("id", "en")

# The site chrome, per language. Only things no page owns live here.
SITE = {
    "id": {
        "name": "C-lite",
        "tagline": "Agent AI pribadi dengan satu inti percakapan",
        "contents": "Isi",
        "edit": "Sunting halaman ini",
        "other": "English",
        "home": "Beranda",
    },
    "en": {
        "name": "C-lite",
        "tagline": "A personal AI agent with one conversation core",
        "contents": "Contents",
        "edit": "Edit this page",
        "other": "Bahasa Indonesia",
        "home": "Home",
    },
}

# Navigation: (section titles per language, slug list). Page labels come from each page's own
# first heading, so the menu and the page cannot disagree. Order is the order here.
NAVIGATION: list[tuple[dict[str, str], list[str]]] = [
    (
        {"id": "Memulai", "en": "Getting started"},
        ["index", "start/install", "start/quickstart"],
    ),
    (
        {"id": "Panduan", "en": "Guides"},
        [
            "guide/configuration",
            "guide/tools",
            "guide/skills",
            "guide/plugins",
            "guide/gateway",
            "guide/security",
        ],
    ),
    (
        {"id": "Rujukan", "en": "Reference"},
        ["reference/commands", "reference/config", "reference/tools"],
    ),
]

HEADING = re.compile(r"^(#{1,4})\s+(.*?)\s*#*\s*$")
FENCE = re.compile(r"^```(\w*)\s*$")
LIST_ITEM = re.compile(r"^\s*([-*]|\d+\.)\s+(.*)$")
TABLE_ROW = re.compile(r"^\s*\|.*\|\s*$")
TABLE_RULE = re.compile(r"^\s*\|(?:\s*:?-{2,}:?\s*\|)+\s*$")
LINK = re.compile(r"(?<!\!)\[([^\]]*)\]\(([^)\s]+)\)")
BOLD = re.compile(r"\*\*([^*]+)\*\*")
ITALIC = re.compile(r"(?<![*\w])\*([^*\n]+)\*(?!\*)")
CODE_SPAN = re.compile(r"`([^`\n]+)`")


def slugify(title: str) -> str:
    """The anchor a heading gets, by the same rules GitHub and ``scripts/doc_refs.py`` use.

    Kept identical to that checker on purpose: a link written as ``page.md#anchor`` is
    checked there against these slugs and resolved here by the browser.
    """
    text = title.strip().replace("`", "").lower()
    return re.sub(r"[^\w\- ]", "", text).replace(" ", "-")


def inline(text: str) -> str:
    """One line of Markdown as HTML: code spans, links, bold and italic.

    Code spans are rendered first and their contents are not touched again, so a backtick in
    the middle of a line protects whatever it holds (the site's own examples do that a lot).
    """
    parts = CODE_SPAN.split(text)
    out = []
    for index, part in enumerate(parts):
        if index % 2:
            out.append(f"<code>{html.escape(part)}</code>")
            continue
        escaped = html.escape(part, quote=False)
        escaped = LINK.sub(lambda match: _link(match.group(1), match.group(2)), escaped)
        escaped = BOLD.sub(r"<strong>\1</strong>", escaped)
        escaped = ITALIC.sub(r"<em>\1</em>", escaped)
        out.append(escaped)
    return "".join(out)


def _link(label: str, target: str) -> str:
    """A Markdown link as HTML, with ``.md`` rewritten to ``.html``.

    A ``#anchor`` alone stays on the page; an unchanged ``.md`` target would 404 on the site,
    which is the one mistake the author cannot see while writing.
    """
    href = target
    if not target.startswith(("http://", "https://", "mailto:")):
        path_part, separator, anchor = target.partition("#")
        if path_part.endswith(".md"):
            path_part = path_part[: -len(".md")] + ".html"
        href = path_part + separator + anchor
    if href.startswith(("http://", "https://")):
        return f'<a href="{html.escape(href, quote=True)}">{label}</a>'
    return f'<a href="{html.escape(href, quote=True)}">{label}</a>'


def render(markdown: str, *, source: str) -> str:
    """The body of a page as HTML. Raises ``ValueError`` on something the renderer cannot
    read, naming ``source`` and the line, so a typo fails the build instead of shipping."""
    lines = markdown.splitlines()
    out: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.strip():
            index += 1
            continue
        fence = FENCE.match(line.strip())
        if fence:
            language = fence.group(1)
            index += 1
            block: list[str] = []
            while index < len(lines) and not lines[index].strip().startswith("```"):
                block.append(lines[index])
                index += 1
            if index >= len(lines):
                raise ValueError(f"{source}:{index + 1}: a code fence is never closed")
            index += 1
            code = html.escape("\n".join(block))
            kind = f' class="language-{language}"' if language else ""
            out.append(f"<pre><code{kind}>{code}</code></pre>")
            continue
        heading = HEADING.match(line)
        if heading:
            level = len(heading.group(1))
            title = heading.group(2)
            out.append(f'<h{level} id="{slugify(title)}">{inline(title)}</h{level}>')
            index += 1
            continue
        if line.strip() in {"---", "***", "___"}:
            out.append("<hr>")
            index += 1
            continue
        if TABLE_ROW.match(line) and index + 1 < len(lines) and TABLE_RULE.match(lines[index + 1]):
            header = _cells(line)
            index += 2
            rows = []
            while index < len(lines) and TABLE_ROW.match(lines[index]):
                rows.append(_cells(lines[index]))
                index += 1
            out.append("<table><thead><tr>")
            out += [f"<th>{inline(cell)}</th>" for cell in header]
            out.append("</tr></thead><tbody>")
            for row in rows:
                out.append("<tr>")
                out += [f"<td>{inline(cell)}</td>" for cell in row]
                out.append("</tr>")
            out.append("</tbody></table>")
            continue
        if line.strip().startswith(">"):
            quote: list[str] = []
            while index < len(lines) and lines[index].strip().startswith(">"):
                quote.append(lines[index].strip().lstrip(">").strip())
                index += 1
            out.append(f"<blockquote><p>{inline(' '.join(quote))}</p></blockquote>")
            continue
        if LIST_ITEM.match(line):
            ordered = bool(re.match(r"^\s*\d+\.", line))
            items: list[str] = []
            while index < len(lines):
                item = LIST_ITEM.match(lines[index])
                if not item or bool(re.match(r"^\s*\d+\.", lines[index])) != ordered:
                    break
                items.append(item.group(2))
                index += 1
            tag = "ol" if ordered else "ul"
            rendered = "".join(f"<li>{inline(item)}</li>" for item in items)
            out.append(f"<{tag}>{rendered}</{tag}>")
            continue
        paragraph: list[str] = []
        while index < len(lines) and lines[index].strip() and not _starts_block(lines[index]):
            paragraph.append(lines[index].strip())
            index += 1
        if not paragraph:  # a construct the renderer does not know; say which
            raise ValueError(f"{source}:{index + 1}: cannot render: {line.strip()!r}")
        out.append(f"<p>{inline(' '.join(paragraph))}</p>")
    return "\n".join(out)


def _starts_block(line: str) -> bool:
    return bool(
        HEADING.match(line)
        or FENCE.match(line.strip())
        or LIST_ITEM.match(line)
        or TABLE_ROW.match(line)
        or line.strip().startswith(">")
        or line.strip() in {"---", "***", "___"}
    )


def _cells(row: str) -> list[str]:
    """The cells of a table row. ``\\|`` inside a cell is a literal pipe, not a separator, which
    is how the generated reference pages escape one."""
    return [cell.strip().replace("\\|", "|") for cell in re.split(r"(?<!\\)\|", row.strip().strip("|"))]


def title_of(markdown: str, *, source: str) -> str:
    for line in markdown.splitlines():
        heading = HEADING.match(line)
        if heading and len(heading.group(1)) == 1:
            return heading.group(2)
    raise ValueError(f"{source}: a page must start with a '# ' heading")


def page_html(*, language: str, slug: str, body: str, title: str, navigation: list[tuple[str, str, str]]) -> str:
    """One page, wrapped in the site chrome. ``navigation`` is ``(href, label, section)``."""
    site = SITE[language]
    depth = 1 + slug.count("/")
    up = "../" * depth
    other = "en" if language == "id" else "id"
    source = f"website/content/{language}/{slug}.md"
    menu = []
    current_section = None
    for href, label, section in navigation:
        if section != current_section:
            current_section = section
            menu.append(f'<p class="section">{html.escape(section)}</p>')
        here = href == f"{slug}.html"
        menu.append(
            f'<a class="{"here" if here else ""}" href="{up}{language}/{href}">{html.escape(label)}</a>'
        )
    return f"""<!doctype html>
<html lang="{language}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)} · {html.escape(site["name"])}</title>
<link rel="stylesheet" href="{up}style.css">
</head>
<body>
<header class="top">
<a class="brand" href="{up}{language}/index.html">{html.escape(site["name"])}</a>
<nav class="languages"><a href="{up}{other}/{slug}.html">{html.escape(site["other"])}</a></nav>
</header>
<div class="layout">
<aside>
<p class="section">{html.escape(site["contents"])}</p>
{"".join(menu)}
</aside>
<main>
{body}
</main>
</div>
<footer>
<a href="{up}{other}/{slug}.html">{html.escape(site["other"])}</a>
<span class="spacer">·</span>
<a href="https://github.com/dragovics/clite/blob/main/{source}">{html.escape(site["edit"])}</a>
</footer>
</body>
</html>
"""


def slugs() -> list[str]:
    """Every page slug, from the navigation, checked against the content trees."""
    found = [slug for _titles, items in NAVIGATION for slug in items]
    if len(set(found)) != len(found):
        raise ValueError("a page is listed twice in NAVIGATION")
    return found


def read_page(language: str, slug: str) -> str:
    path = CONTENT / language / f"{slug}.md"
    if not path.is_file():
        raise ValueError(f"{path.relative_to(ROOT)} is missing")
    return path.read_text(encoding="utf-8")


def navigation_for(language: str) -> list[tuple[str, str, str]]:
    """``(href, label, section)`` for the menu, labelled with each page's own title."""
    items = []
    for titles, slugs_in_section in NAVIGATION:
        for slug in slugs_in_section:
            title = title_of(read_page(language, slug), source=f"{language}/{slug}.md")
            items.append((f"{slug}.html", title, titles[language]))
    return items


def build(out: Path) -> list[Path]:
    """Write the whole site to ``out`` and return the files written."""
    written: list[Path] = []
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for language in LANGUAGES:
        navigation = navigation_for(language)
        for slug in slugs():
            markdown = read_page(language, slug)
            source = f"{language}/{slug}.md"
            body = render(markdown, source=source)
            page = page_html(
                language=language,
                slug=slug,
                body=body,
                title=title_of(markdown, source=source),
                navigation=navigation,
            )
            target = out / language / f"{slug}.html"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(page, encoding="utf-8")
            written.append(target)
    for asset in sorted(STATIC.rglob("*")):
        if asset.is_file():
            destination = out / asset.relative_to(STATIC)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(asset, destination)
            written.append(destination)
    index = out / "index.html"
    index.write_text(root_html(), encoding="utf-8")
    written.append(index)
    return written


def root_html() -> str:
    """The landing page at the root of the site: pick a language, no redirect.

    A meta refresh would decide for the reader and break the back button; one page with two
    links costs nothing.
    """
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>C-lite</title>
<link rel="stylesheet" href="style.css">
</head>
<body class="chooser">
<main>
<h1>C-lite</h1>
<p>{html.escape(SITE["id"]["tagline"])}</p>
<p>{html.escape(SITE["en"]["tagline"])}</p>
<ul>
<li><a href="id/index.html">Dokumentasi bahasa Indonesia</a></li>
<li><a href="en/index.html">Documentation in English</a></li>
</ul>
</main>
</body>
</html>
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory")
    parser.add_argument(
        "--check", action="store_true", help="render every page and exit 1 if one cannot be built"
    )
    args = parser.parse_args(argv)
    out = args.out if args.out.is_absolute() else (ROOT / args.out)
    try:
        written = build(out)
    except ValueError as exc:
        print(f"{exc}", file=sys.stderr)
        return 1
    if args.check:
        print(f"{len(written)} pages render")
        return 0
    for path in written:
        print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
